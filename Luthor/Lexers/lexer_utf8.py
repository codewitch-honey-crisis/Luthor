pos = 0
while pos < len(units):
    at_line_start = pos == 0 or units[pos - 1] == DFA[0]
    tok, length = match(DFA, units, pos, at_line_start)
    if tok != 5:
        print(f"{NAMES[tok]:<9} " + units[pos:pos + length].decode("utf-8", "replace").replace("\n", "\\n"))
    pos += length
